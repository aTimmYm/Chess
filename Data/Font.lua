local textRunsCache = {}

local UPPER_MAP = {
	["а"]="А", ["б"]="Б", ["в"]="В", ["г"]="Г", ["д"]="Д",
	["е"]="Е", ["ё"]="Ё", ["є"]="Є", ["ж"]="Ж", ["з"]="З",
	["и"]="И", ["і"]="І", ["ї"]="Ї", ["й"]="Й", ["к"]="К",
	["л"]="Л", ["м"]="М", ["н"]="Н", ["о"]="О", ["п"]="П",
	["р"]="Р", ["с"]="С", ["т"]="Т", ["у"]="У", ["ф"]="Ф",
	["х"]="Х", ["ц"]="Ц", ["ч"]="Ч", ["ш"]="Ш", ["щ"]="Щ",
	["ъ"]="Ъ", ["ы"]="Ы", ["ь"]="Ь", ["э"]="Э", ["ю"]="Ю", ["я"]="Я",
}

local LOWER_MAP = {}
for k, v in pairs(UPPER_MAP) do
	LOWER_MAP[v] = k
end

local function utf8_chars(str)
	local i, n = 1, #str
	return function()
		if i > n then return nil end
		local b = _byte(str, i)
		if not b then return nil end

		-- Визначаємо довжину символу в байтах
		local len = 1
		if b >= 0xC0 and b <= 0xDF then len = 2
		elseif b >= 0xE0 and b <= 0xEF then len = 3
		elseif b >= 0xF0 and b <= 0xF7 then len = 4
		end

		local ch = _sub(str, i, i + len - 1)
		i = i + len
		return ch
	end
end

function Font.upper(str)
	local result = {}
	for ch in utf8_chars(str) do
		if UPPER_MAP[ch] then
			t_insert(result, UPPER_MAP[ch])
		else
			t_insert(result, string.upper(ch))
		end
	end
	return t_concat(result)
end

function Font.lower(str)
	local result = {}
	for ch in utf8_chars(str) do
		if LOWER_MAP[ch] then
			t_insert(result, LOWER_MAP[ch])
		else
			t_insert(result, string.lower(ch))
		end
	end
	return t_concat(result)
end

local glyphWidthCache = {}
local glyphRunsCache = {}

function Font.clearCache()
	glyphWidthCache = {}
	glyphRunsCache = {}
	textRunsCache = {}
end

function Font.setGlyphs(glyphTable)
	Font.glyphs = glyphTable or {}
	Font.clearCache()
end

local function getBoldExtra(bold)
	return (bold == true and 1) or (type(bold) == "number" and bold or 0)
end

local function getGlyph(ch)
	if Font.glyphs[ch] then
		return Font.glyphs[ch]
	end

	local bytes = {}
	for i = 1, #ch do
		t_insert(bytes, tostring(_byte(ch, i)))
	end

	error("Unknown symbol! Bytes: " .. t_concat(bytes, ", ") .. ' ' .. tostring(ch), 2)
	return Font.glyphs["?"]
end

local function getGlyphWidth(ch)
	local cached = glyphWidthCache[ch]
	if cached then return cached end

	local glyph = getGlyph(ch)
	local maxw = 0
	for row = 1, Font.charHeight do
		local line = glyph[row] or ""
		local lineLen = #line
		if lineLen > maxw then
			maxw = lineLen
		end
	end

	local w = _min(Font.charWidth, maxw)
	glyphWidthCache[ch] = w
	return w
end

local function buildGlyphRects(glyph)
	local rects = {}
	local active = {}

	for row = 1, Font.charHeight do
		local line = glyph[row] or ""
		local rowRuns = {}
		local i = 1

		while i <= #line do
			while i <= #line and line:sub(i, i) ~= "#" do
				i = i + 1
			end
			if i > #line then break end

			local x = i
			while i <= #line and line:sub(i, i) == "#" do
				i = i + 1
			end

			rowRuns[#rowRuns + 1] = {
				x = x,
				w = i - x
			}
		end

		local nextActive = {}

		for _, run in ipairs(rowRuns) do
			local key = run.x .. ":" .. run.w
			local rect = active[key]

			if rect and rect.y + rect.h == row - 1 then
				rect.h = rect.h + 1
				nextActive[key] = rect
			else
				rect = {
					x = run.x - 1,
					y = row - 1,
					w = run.w,
					h = 1
				}
				rects[#rects + 1] = rect
				nextActive[key] = rect
			end
		end

		active = nextActive
	end

	return rects
end

local function getGlyphRects(ch)
	local cached = glyphRunsCache[ch]
	if cached then return cached end

	local glyph = getGlyph(ch)
	cached = buildGlyphRects(glyph)
	glyphRunsCache[ch] = cached
	return cached
end

local function buildTextRuns(text)
	local cached = textRunsCache[text]
	if cached then return cached end

	local runs = {}
	local px = 0

	for ch in utf8_chars(text) do
		local glyphRects = getGlyphRects(ch)
		local len = getGlyphWidth(ch)

		for i = 1, #glyphRects do
			local r = glyphRects[i]
			runs[#runs + 1] = {
				x = px + r.x,
				y = r.y,
				w = r.w,
				h = r.h,
			}
		end

		px = px + len + Font.interval
	end

	cached = {
		runs = runs,
		width = px
	}

	textRunsCache[text] = cached
	return cached
end

function Font.calcWidth(text, isbold, scale)
	scale = scale and _max(1, _min(10, scale)) or 1
	if not utf8.len(text) then
		error('Invalid character in: \'' .. tostring(text) .. '\', bytes: ' .. tostring(_byte(text)), 2)
	end

	local px = 0
	local bold_extra = getBoldExtra(isbold)

	for ch in utf8_chars(text) do
		local len = getGlyphWidth(ch)
		px = px + _ceil(scale * len + Font.interval * scale) + bold_extra
	end

	if px > 0 then
		px = px - Font.interval * scale
	end

	return _max(0, px)
end

---Function draws text in term.setGraphicsMode(1)
---@param text string Text that should be written
---@param x number
---@param y number
---@param fc color Text color
---@param w? number
---@param h? number
---@param align? string Enter w and h to use. Combine 'top', 'bot', 'center', 'left' and 'right' to select align. Example 'top_right', 'botleft'; 'center' is default value for that param.
---@param scale? integer integer >= 1
---@return nil
function Font.drawText(text, x, y, fc, w, h, align, scale)
	scale = scale and _max(1, _min(10, scale)) or 1
	if align and w and h then
		local textWidth = Font.calcWidth(text, bold, scale)
		local dx = w - textWidth
		local dy = h - Font.charHeight * scale

		local X, Y = x, y
		x = X + _floor(dx / 2)
		y = Y + _floor(dy / 2)

		if align:find('left', 1, true) then
			x = X
		elseif align:find('right', 1, true) then
			x = X + dx
		end

		if align:find('top', 1, true) then
			y = Y
		elseif align:find('bot', 1, true) or align:find('bottom', 1, true) then
			y = Y + dy
		end
	end

	local data = buildTextRuns(text)

	local runs = data.runs

	for i = 1, #runs do
		local r = runs[i]
		term.drawPixels(
			x + r.x,
			y + r.y,
			fc,
			r.w,
			r.h
		)
	end
end

function Font.simpleText(text, x, y, fc, w, h, align)
	return Font.drawText(text, x, y, fc, w, h, align)
end

function Font.write(text)
	local x, y = term.getCursorPos()
	return Font.drawText(text, x, y, term.getTextColor())
end

